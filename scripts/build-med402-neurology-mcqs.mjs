import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSource = 'G:\\school\\study mode\\subjects\\402\\fresh\\neuro_question_bank.json'
const sourcePath = path.resolve(process.argv[2] || defaultSource)
const targetPaths = [
  path.join(repoRoot, 'src', 'med402-neurology-mcqs.js'),
  path.join(repoRoot, 'public', 'src', 'med402-neurology-mcqs.js')
]

const chapterDefinitions = [
  { name: 'Introduction of Neuro', id: 'introduction-of-neuro', label: 'Introduction of Neuro' },
  { name: 'Speech and Cranial Nerve', id: 'speech-and-cranial-nerve', label: 'Speech and Cranial Nerve' },
  { name: 'Hemiplegia', id: 'hemiplegia', label: 'Hemiplegia' },
  { name: 'Pathogenesis of Cerebral Vascular Insufficiency', id: 'cerebral-vascular-insufficiency', label: 'Cerebral Vascular Insufficiency' },
  { name: 'Paraplegia', id: 'paraplegia', label: 'Paraplegia' }
]

function cleanText(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:?!])/g, '$1')
    .trim()
}

function normalizeAnswer(answer) {
  const value = cleanText(answer)
  if (/^true$/i.test(value)) return 'T'
  if (/^false$/i.test(value)) return 'F'
  return value
}

function parseQuestion(question) {
  const chapter = chapterDefinitions.find((item) => item.name === question.chapter)
  const choices = Array.isArray(question.options)
    ? question.options.map((option) => ({
      label: cleanText(option.label),
      text: cleanText(option.text)
    }))
    : []
  const answer = normalizeAnswer(question.answer)
  const answerIndex = choices.findIndex((choice) => choice.label === answer)
  const source = cleanText(question.source || `Neurology Midterm Question Bank - Q${question.id}`)
  const questionText = cleanText(question.question)

  if (!chapter || !questionText || choices.length < 2 || answerIndex < 0) {
    return {
      held: {
        chapter: question.chapter || '',
        originalNumber: String(question.id),
        question: questionText,
        choices: choices.map((choice) => choice.text),
        answer: cleanText(question.answer),
        source,
        reason: choices.length < 2
          ? `Incomplete source record: ${choices.length} choices`
          : `Unresolved answer "${cleanText(question.answer)}"`
      }
    }
  }

  return {
    parsed: {
      id: `med402-neuro-q${String(question.id).padStart(3, '0')}`,
      originalNumber: String(question.id),
      category: chapter.label,
      organ: chapter.label,
      question: questionText,
      choices: choices.map((choice) => choice.text),
      answerIndex,
      explanation: `Answer: ${choices[answerIndex].text}.`,
      source,
      section: `${chapter.label} - ${source}`,
      topicTags: ['MED402-2', 'Neurology', chapter.label]
    }
  }
}

function createParts(chapter, sourceId) {
  const partSize = chapter.questions.length > 30 ? Math.ceil(chapter.questions.length / Math.ceil(chapter.questions.length / 30)) : Math.ceil(chapter.questions.length / 2)
  const parts = []

  for (let offset = 0; offset < chapter.questions.length; offset += partSize) {
    const questions = chapter.questions.slice(offset, offset + partSize)
    const index = parts.length
    parts.push({
      id: `med402-neuro-${chapter.id}-p${String(index + 1).padStart(2, '0')}`,
      label: `Part ${index + 1} - Q${questions[0].originalNumber}-${questions.at(-1).originalNumber}`,
      description: `${chapter.label} questions`,
      range: `Q${questions[0].originalNumber}-${questions.at(-1).originalNumber}`,
      questionStart: Number(questions[0].originalNumber),
      questionEnd: Number(questions.at(-1).originalNumber),
      parentSourceId: sourceId,
      groupId: chapter.id,
      groupLabel: chapter.label,
      partIndex: index,
      partCount: Math.ceil(chapter.questions.length / partSize),
      shuffleQuestions: false,
      shuffleOptions: false,
      mcqs: questions
    })
  }

  return parts
}

function buildGeneratedSource(chapters, heldForReview, sourceHash) {
  const sourceId = 'med402-neurology-question-bank'
  const questions = chapters.flatMap((chapter) => chapter.questions)
  const groups = chapters.map((chapter) => ({
    id: chapter.id,
    label: chapter.label,
    questionCount: chapter.questions.length,
    parts: createParts(chapter, sourceId)
  }))
  const partCount = groups.reduce((total, group) => total + group.parts.length, 0)

  return `// Generated by scripts/build-med402-neurology-mcqs.mjs.
// Source SHA-256: ${sourceHash}
// Included: ${questions.length} answer-keyed neurology questions across ${chapters.length} chapters.
(() => {
  const quizzes = window.mcqQuizzes402 || (window.mcqQuizzes402 = {})
  const quiz = quizzes["MED 402-2 MCQs"] || (quizzes["MED 402-2 MCQs"] = { alwaysShowSourcePicker: true, sources: [] })
  quiz.alwaysShowSourcePicker = true

  const source = ${JSON.stringify({
    id: sourceId,
    label: 'Neurology Question Bank',
    description: `${questions.length} questions - ${chapters.length} chapters - ${partCount} short parts`,
    shuffleQuestions: false,
    shuffleOptions: false,
    mcqs: questions,
    heldForReview,
    collection: {
      prompt: 'Choose a neurology chapter or a revision mode.',
      groupNoun: 'chapter',
      groupEyebrow: 'MED402-2 neurology',
      mixedMeta: 'Random questions from the MED402-2 neurology bank.',
      mixedSizes: [
        { id: 'quick-20', label: 'Quick 20', size: 20, description: 'A short mixed neurology session.' },
        { id: 'standard-30', label: 'Standard 30', size: 30, description: 'Balanced neurology practice.' },
        { id: 'exam-50', label: 'Exam 50', size: 50, description: 'A longer mixed neurology session.' }
      ],
      wrongReviewId: 'med402-neurology-wrong-review',
      groups
    }
  }, null, 2)}

  quiz.sources = (quiz.sources || []).filter((item) => item.id !== source.id)
  quiz.sources.push(source)
})()
`
}

const json = await readFile(sourcePath, 'utf8')
const bank = JSON.parse(json)
const byChapter = Object.fromEntries(chapterDefinitions.map((chapter) => [chapter.name, { ...chapter, questions: [] }]))
const heldForReview = []

for (const rawQuestion of bank.questions || []) {
  const result = parseQuestion(rawQuestion)
  if (result.parsed) {
    byChapter[rawQuestion.chapter].questions.push(result.parsed)
  } else {
    heldForReview.push(result.held)
  }
}

const chapters = chapterDefinitions.map((chapter) => byChapter[chapter.name])
const questions = chapters.flatMap((chapter) => chapter.questions)

if (bank.total_questions !== 323 || (bank.questions || []).length !== 323) {
  throw new Error(`Expected 323 source records, got ${bank.questions?.length || 0}`)
}
if (questions.length + heldForReview.length !== 323) {
  throw new Error(`Expected 323 accounted records, got ${questions.length} included and ${heldForReview.length} held`)
}
if (questions.length !== 269 || heldForReview.length !== 54) {
  throw new Error(`Expected 269 included and 54 held, got ${questions.length} included and ${heldForReview.length} held`)
}
if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated MED402 neurology question IDs are not unique')
}
if (questions.some((question) => question.choices.length < 2 || !question.choices[question.answerIndex])) {
  throw new Error('Generated MED402 neurology questions contain an invalid answer')
}

const sourceHash = createHash('sha256').update(json).digest('hex')
const generatedSource = buildGeneratedSource(chapters, heldForReview, sourceHash)
await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))

