import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSource = 'C:\\Users\\ahmed\\Downloads\\Telegram Desktop\\psychiatry_question_bank.json'
const sourcePath = path.resolve(process.argv[2] || defaultSource)
const targetPaths = [
  path.join(repoRoot, 'src', 'med402-psychiatry-question-bank.js'),
  path.join(repoRoot, 'public', 'src', 'med402-psychiatry-question-bank.js')
]

const sourceId = 'med402-psychiatry-question-bank'
const sourceLabel = 'psychiatry_question_bank'
const maxPartSize = 30

function cleanText(value) {
  return String(value ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:?!])/g, '$1')
    .trim()
}

function parseSource(sourceContent) {
  const data = JSON.parse(sourceContent)
  if (!Array.isArray(data.questions) || !Array.isArray(data.chapters)) {
    throw new Error('Invalid JSON structure: expected questions and chapters arrays')
  }

  const chapterOrder = data.chapters.map((chapter) => cleanText(chapter.name))
  const chapterQuestions = new Map(chapterOrder.map((chapter) => [chapter, []]))
  const questions = []
  const heldForReview = []

  for (const record of data.questions) {
    const originalNumber = String(record.number ?? '')
    const chapter = cleanText(record.chapter)
    const questionText = cleanText(record.question)
    const optionEntries = Object.entries(record.options || {})
    const answerKey = cleanText(record.answer)
    const answerIndex = optionEntries.findIndex(([key]) => key === answerKey)

    if (!chapterQuestions.has(chapter)) {
      throw new Error(`Question ${originalNumber} has unknown chapter ${JSON.stringify(chapter)}`)
    }

    if (record.type === 'matching') {
      heldForReview.push({
        originalNumber,
        chapter,
        type: record.type,
        question: questionText,
        answer: record.answer,
        source: cleanText(record.source),
        reason: 'Matching question requires multiple answers and is not compatible with the one-answer quiz format'
      })
      continue
    }

    if (optionEntries.length < 2 || answerIndex < 0) {
      heldForReview.push({
        originalNumber,
        chapter,
        type: cleanText(record.type),
        question: questionText,
        choices: optionEntries.map(([, value]) => cleanText(value)),
        answer: record.answer,
        note: cleanText(record.note),
        source: cleanText(record.source),
        reason: answerIndex < 0
          ? 'Answer key does not identify exactly one supplied option'
          : 'Fewer than two options were supplied'
      })
      continue
    }

    const choices = optionEntries.map(([, value]) => cleanText(value))
    const explanationParts = [`Answer: ${choices[answerIndex]}.`]
    if (record.note) explanationParts.push(`Source note: ${cleanText(record.note)}`)

    const question = {
      id: `med402-psychiatry-bank-q${originalNumber.padStart(3, '0')}`,
      originalNumber,
      category: 'Psychiatry',
      organ: 'Psychiatry',
      question: questionText,
      choices,
      answerIndex,
      explanation: explanationParts.join(' '),
      source: `${cleanText(record.source) || 'Source not specified'} - Q${originalNumber}`,
      section: `Psychiatry - ${chapter}`,
      topicTags: ['MED402-2', 'Psychiatry', chapter]
    }

    questions.push(question)
    chapterQuestions.get(chapter).push(question)
  }

  return { questions, heldForReview, chapterOrder, chapterQuestions }
}

function buildParts(chapter, questions) {
  const partCount = Math.ceil(questions.length / maxPartSize)
  return Array.from({ length: partCount }, (_, partIndex) => {
    const partQuestions = questions.slice(partIndex * maxPartSize, (partIndex + 1) * maxPartSize)
    const firstQuestion = partQuestions[0].originalNumber
    const lastQuestion = partQuestions.at(-1).originalNumber
    const suffix = partCount > 1 ? ` - Part ${partIndex + 1}` : ''

    return {
      id: `med402-psychiatry-bank-${chapter.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-p${partIndex + 1}`,
      label: `${chapter}${suffix}`,
      description: `${partQuestions.length} questions`,
      range: `Q${firstQuestion}-Q${lastQuestion}`,
      questionStart: Number(firstQuestion),
      questionEnd: Number(lastQuestion),
      parentSourceId: sourceId,
      groupId: chapter.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
      groupLabel: chapter,
      partIndex,
      partCount,
      shuffleQuestions: false,
      shuffleOptions: false,
      mcqs: partQuestions
    }
  })
}

function buildGeneratedSource(questions, heldForReview, groups, sourceHash) {
  const parts = groups.flatMap((group) => group.parts)

  return `// Generated by scripts/build-med402-psychiatry-question-bank.mjs.
// Source SHA-256: ${sourceHash}
// Included: ${questions.length} answer-safe questions; held: ${heldForReview.length}.
(() => {
  const quizzes = window.mcqQuizzes402 || (window.mcqQuizzes402 = {})
  const quiz = quizzes["MED 402-2 MCQs"] || (quizzes["MED 402-2 MCQs"] = { alwaysShowSourcePicker: true, sources: [] })
  quiz.alwaysShowSourcePicker = true

  const source = ${JSON.stringify({
    id: sourceId,
    label: sourceLabel,
    description: `${questions.length} questions - 4 chapters - ${parts.length} short parts`,
    shuffleQuestions: false,
    shuffleOptions: false,
    mcqs: questions,
    heldForReview,
    collection: {
      prompt: 'Choose a psychiatry chapter or a revision mode.',
      groupNoun: 'chapter',
      groupEyebrow: 'MED402-2 psychiatry',
      mixedMeta: `Random questions from ${sourceLabel}.`,
      mixedSizes: [
        { id: 'quick-20', label: 'Quick 20', size: 20, description: 'A short mixed psychiatry session.' },
        { id: 'standard-30', label: 'Standard 30', size: 30, description: 'Balanced psychiatry practice.' },
        { id: 'full-117', label: 'Full 117', size: questions.length, description: `Solve all ${questions.length} answer-safe questions.` }
      ],
      wrongReviewId: 'med402-psychiatry-question-bank-wrong-review',
      groups
    }
  }, null, 2)}

  quiz.sources = (quiz.sources || []).filter((item) => item.id !== source.id)
  quiz.sources.push(source)
})()
`
}

const sourceContent = await readFile(sourcePath, 'utf8')
const sourceHash = createHash('sha256').update(sourceContent).digest('hex')
const { questions, heldForReview, chapterOrder, chapterQuestions } = parseSource(sourceContent)
const groups = chapterOrder.map((chapter) => {
  const questionsForChapter = chapterQuestions.get(chapter)
  return {
    id: chapter.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    label: chapter,
    questionCount: questionsForChapter.length,
    parts: buildParts(chapter, questionsForChapter)
  }
})

if (questions.length + heldForReview.length !== 128) {
  throw new Error(`Expected 128 total records, got ${questions.length + heldForReview.length}`)
}
if (questions.length !== 117 || heldForReview.length !== 11) {
  throw new Error(`Expected 117 included and 11 held, got ${questions.length} included and ${heldForReview.length} held`)
}
if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated question IDs are not unique')
}
if (questions.some((question) => question.choices.length < 2 || !question.choices[question.answerIndex])) {
  throw new Error('Generated questions contain an invalid answer')
}

const generatedSource = buildGeneratedSource(questions, heldForReview, groups, sourceHash)
await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))

