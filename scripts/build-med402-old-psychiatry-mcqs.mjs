import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSource = 'C:\\Users\\ahmed\\.codex\\attachments\\4f234c46-a1dc-4a38-97b0-06cb3cf76ff1\\pasted-text.txt'
const sourcePath = path.resolve(process.argv[2] || defaultSource)
const targetPaths = [
  path.join(repoRoot, 'src', 'med402-old-psychiatry-mcqs.js'),
  path.join(repoRoot, 'public', 'src', 'med402-old-psychiatry-mcqs.js')
]

function cleanText(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:?!])/g, '$1')
    .trim()
}

function extractItems(sourceText) {
  return Array.from(sourceText.matchAll(/"""([\s\S]*?)"""/g), (match) => match[1])
}

function parseItem(itemText) {
  const lines = itemText
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)

  const firstLine = lines.shift() || ''
  const firstMatch = firstLine.match(/^(\d+)\.\s*(.*)$/)
  const originalNumber = firstMatch?.[1] || ''
  const questionLines = [firstMatch?.[2] || firstLine]
  const options = []
  let answer = ''

  for (const line of lines) {
    const answerMatch = line.match(/^Marked answer:\s*([A-Z])\s*$/i)
    if (answerMatch) {
      answer = answerMatch[1].toUpperCase()
      continue
    }

    const optionMatch = line.match(/^([A-Z])\.\s*(.*)$/)
    if (optionMatch) {
      options.push({
        label: optionMatch[1].toUpperCase(),
        text: cleanText(optionMatch[2])
      })
      continue
    }

    questionLines.push(line)
  }

  return {
    originalNumber,
    question: cleanText(questionLines.join(' ')),
    options,
    answer
  }
}

function parseQuestion(rawQuestion) {
  const choices = rawQuestion.options
  const answerIndex = choices.findIndex((choice) => choice.label === rawQuestion.answer)
  const source = `Old psychiatry marked MCQs - Q${rawQuestion.originalNumber}`

  if (!rawQuestion.originalNumber || !rawQuestion.question || choices.length < 1 || answerIndex < 0) {
    return {
      held: {
        originalNumber: rawQuestion.originalNumber,
        question: rawQuestion.question,
        choices: choices.map((choice) => choice.text),
        answer: rawQuestion.answer,
        source,
        reason: choices.length < 1
          ? `Incomplete source record: ${choices.length} choices`
          : `Unresolved answer "${rawQuestion.answer}"`
      }
    }
  }

  return {
    parsed: {
      id: `med402-old-psych-q${String(rawQuestion.originalNumber).padStart(3, '0')}`,
      originalNumber: rawQuestion.originalNumber,
      category: 'Psychiatry',
      organ: 'Psychiatry',
      question: rawQuestion.question,
      choices: choices.map((choice) => choice.text),
      answerIndex,
      explanation: `Answer: ${choices[answerIndex].text}.`,
      source,
      section: `Psychiatry - ${source}`,
      topicTags: ['MED402-2', 'Psychiatry']
    }
  }
}

function createParts(questions, sourceId) {
  const partSize = 30
  const parts = []

  for (let offset = 0; offset < questions.length; offset += partSize) {
    const partQuestions = questions.slice(offset, offset + partSize)
    const index = parts.length
    parts.push({
      id: `med402-old-psychiatry-p${String(index + 1).padStart(2, '0')}`,
      label: `Part ${index + 1} - Q${partQuestions[0].originalNumber}-${partQuestions.at(-1).originalNumber}`,
      description: 'Old psychiatry MCQs',
      range: `Q${partQuestions[0].originalNumber}-${partQuestions.at(-1).originalNumber}`,
      questionStart: Number(partQuestions[0].originalNumber),
      questionEnd: Number(partQuestions.at(-1).originalNumber),
      parentSourceId: sourceId,
      groupId: 'psychiatry',
      groupLabel: 'Psychiatry',
      partIndex: index,
      partCount: Math.ceil(questions.length / partSize),
      shuffleQuestions: false,
      shuffleOptions: false,
      mcqs: partQuestions
    })
  }

  return parts
}

function buildGeneratedSource(questions, heldForReview, sourceHash) {
  const sourceId = 'med402-old-psychiatry-mcqs'
  const parts = createParts(questions, sourceId)

  return `// Generated by scripts/build-med402-old-psychiatry-mcqs.mjs.
// Source SHA-256: ${sourceHash}
// Included: ${questions.length} answer-keyed old psychiatry questions.
(() => {
  const quizzes = window.mcqQuizzes402 || (window.mcqQuizzes402 = {})
  const quiz = quizzes["MED 402-2 MCQs"] || (quizzes["MED 402-2 MCQs"] = { alwaysShowSourcePicker: true, sources: [] })
  quiz.alwaysShowSourcePicker = true

  const source = ${JSON.stringify({
    id: sourceId,
    label: 'Old Psychiatry MCQs',
    description: `${questions.length} questions - 1 section - ${parts.length} short parts`,
    shuffleQuestions: false,
    shuffleOptions: false,
    mcqs: questions,
    heldForReview,
    collection: {
      prompt: 'Choose an old psychiatry part or a revision mode.',
      groupNoun: 'section',
      groupEyebrow: 'MED402-2 psychiatry',
      mixedMeta: 'Random questions from the old psychiatry MCQs.',
      mixedSizes: [
        { id: 'quick-20', label: 'Quick 20', size: 20, description: 'A short mixed psychiatry session.' },
        { id: 'standard-30', label: 'Standard 30', size: 30, description: 'Balanced psychiatry practice.' },
        { id: 'full-67', label: 'Full 67', size: 67, description: 'Solve the full old psychiatry set.' }
      ],
      wrongReviewId: 'med402-old-psychiatry-wrong-review',
      groups: [
        {
          id: 'psychiatry',
          label: 'Psychiatry',
          questionCount: questions.length,
          parts
        }
      ]
    }
  }, null, 2)}

  quiz.sources = (quiz.sources || []).filter((item) => item.id !== source.id)
  quiz.sources.push(source)
})()
`
}

const sourceText = await readFile(sourcePath, 'utf8')
const rawQuestions = extractItems(sourceText).map(parseItem)
const heldForReview = []
const questions = []

for (const rawQuestion of rawQuestions) {
  const result = parseQuestion(rawQuestion)
  if (result.parsed) {
    questions.push(result.parsed)
  } else {
    heldForReview.push(result.held)
  }
}

if (rawQuestions.length !== 67) {
  throw new Error(`Expected 67 source records, got ${rawQuestions.length}`)
}
if (questions.length + heldForReview.length !== 67) {
  throw new Error(`Expected 67 accounted records, got ${questions.length} included and ${heldForReview.length} held`)
}
if (questions.length !== 67 || heldForReview.length !== 0) {
  throw new Error(`Expected 67 included and 0 held, got ${questions.length} included and ${heldForReview.length} held`)
}
if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated old psychiatry question IDs are not unique')
}
if (questions.some((question) => question.choices.length < 1 || !question.choices[question.answerIndex])) {
  throw new Error('Generated old psychiatry questions contain an invalid answer')
}

const sourceHash = createHash('sha256').update(sourceText).digest('hex')
const generatedSource = buildGeneratedSource(questions, heldForReview, sourceHash)
await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))

