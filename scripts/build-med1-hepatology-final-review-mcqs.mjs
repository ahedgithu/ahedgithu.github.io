import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSourcePath = 'C:\\Users\\ahmed\\Downloads\\Telegram Desktop\\Hepatology_Liver_Diseases_Final_Review.json'
const sourcePath = path.resolve(process.argv[2] || defaultSourcePath)
const targetPaths = [
  path.join(repoRoot, 'src', 'med1-hepatology-final-review-mcqs.js'),
  path.join(repoRoot, 'public', 'src', 'med1-hepatology-final-review-mcqs.js')
]

const sourceText = await readFile(sourcePath, 'utf8')
const sourceHash = createHash('sha256').update(sourceText).digest('hex')
const sourceData = JSON.parse(sourceText)
const expectedSubject = 'MED 401-1'
const expectedTopic = 'Hepatology & Liver Diseases'
const expectedCount = 54
const answerIndexes = { A: 0, B: 1, C: 2, D: 3 }

if (sourceData.subject !== expectedSubject || sourceData.topic !== expectedTopic) {
  throw new Error(`Unexpected source destination: ${sourceData.subject} / ${sourceData.topic}`)
}
if (!Array.isArray(sourceData.questions) || sourceData.questions.length !== expectedCount) {
  throw new Error(`Source count mismatch: expected ${expectedCount}, got ${sourceData.questions?.length ?? 0}`)
}

const questions = sourceData.questions.map((record, index) => {
  const answerIndex = answerIndexes[record.correctAnswer]
  if (
    !record.question?.trim() ||
    !Array.isArray(record.choices) ||
    record.choices.length !== 4 ||
    !Number.isInteger(answerIndex) ||
    !record.choices[answerIndex] ||
    !record.explanation?.trim()
  ) {
    throw new Error(`Invalid question record at position ${index + 1}`)
  }

  return {
    id: `med1-hepatology-final-review-q${String(index + 1).padStart(3, '0')}`,
    originalNumber: String(index + 1),
    category: expectedTopic,
    organ: expectedTopic,
    question: record.question.trim(),
    choices: record.choices.map((choice) => choice.trim()),
    answerIndex,
    explanation: record.explanation.trim(),
    source: `${sourceData.source} - Q${index + 1}`,
    section: expectedTopic,
    topicTags: ['MED-1', 'Hepatology', 'Liver Diseases', 'Final Review']
  }
})

if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated question IDs are not unique')
}

const source = {
  id: 'med1-hepatology-final-review',
  label: sourceData.source,
  description: `${questions.length} source-faithful hepatology and liver disease review questions`,
  sourceFile: path.basename(sourcePath),
  sourceHash,
  shuffleQuestions: false,
  shuffleOptions: false,
  mcqs: questions
}

const generatedSource = `// Generated by scripts/build-med1-hepatology-final-review-mcqs.mjs.
// ${path.basename(sourcePath)} SHA-256: ${sourceHash}
// Included: ${questions.length} answer-keyed MED 401-1 hepatology questions.
(() => {
  const quizzes = window.mcqQuizzes || (window.mcqQuizzes = {})
  const quiz = quizzes["MED 401-1 MCQs"] || (quizzes["MED 401-1 MCQs"] = { alwaysShowSourcePicker: true, sources: [] })
  quiz.alwaysShowSourcePicker = true

  const source = ${JSON.stringify(source, null, 2)}
  quiz.sources = (quiz.sources || []).filter((item) => item.id !== source.id)
  quiz.sources.push(source)
})()
`

await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))
console.log(JSON.stringify({
  sourcePath,
  sourceHash,
  included: questions.length,
  outputs: targetPaths
}, null, 2))
