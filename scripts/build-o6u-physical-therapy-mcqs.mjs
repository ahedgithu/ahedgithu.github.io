import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSourcePath = 'G:\\school\\study mode\\subjects\\6oU\\physical therapy\\physiological_adaptations_65_mcqs.json'
const sourcePath = path.resolve(process.argv[2] || defaultSourcePath)
const targetPaths = [
  path.join(repoRoot, 'src', 'o6u-physical-therapy-mcqs.js'),
  path.join(repoRoot, 'public', 'src', 'o6u-physical-therapy-mcqs.js')
]

const sourceText = await readFile(sourcePath, 'utf8')
const sourceHash = createHash('sha256').update(sourceText).digest('hex')
const sourceData = JSON.parse(sourceText)
const expectedSubject = 'Exercise Physiology'
const expectedTopic = 'Physiological Adaptations to Regular Physical Training'
const quizTopicKey = 'PT-PHYS::Physiological Adaptation to Regular Physical Training'
const expectedCount = 65

if (sourceData.subject !== expectedSubject || sourceData.topic !== expectedTopic) {
  throw new Error(`Unexpected source destination: ${sourceData.subject} / ${sourceData.topic}`)
}
if (!Array.isArray(sourceData.questions) || sourceData.questions.length !== expectedCount) {
  throw new Error(`Source count mismatch: expected ${expectedCount}, got ${sourceData.questions?.length ?? 0}`)
}

const questions = sourceData.questions.map((record, index) => {
  const choices = Array.isArray(record.choices)
    ? record.choices.map((choice) => String(choice).trim())
    : []
  const answerIndex = choices.indexOf(String(record.correctAnswer || '').trim())

  if (
    !record.question?.trim() ||
    choices.length !== 4 ||
    answerIndex < 0 ||
    !record.explanation?.trim()
  ) {
    throw new Error(`Invalid question record at position ${index + 1}`)
  }

  return {
    id: `o6u-pt-phys-adaptations-q${String(index + 1).padStart(3, '0')}`,
    originalNumber: String(index + 1),
    category: expectedTopic,
    organ: expectedSubject,
    question: record.question.trim(),
    choices,
    answerIndex,
    explanation: record.explanation.trim(),
    source: `${sourceData.source} - Q${index + 1}`,
    section: expectedTopic,
    topicTags: ['O6U', 'Physical Therapy', 'PT-PHYS', 'Exercise Physiology']
  }
})

if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated question IDs are not unique')
}

const source = {
  id: 'o6u-pt-phys-physiological-adaptations-part-1',
  label: 'Physiological Adaptations — Part 1',
  description: `${questions.length} source-faithful Exercise Physiology questions`,
  sourceFile: path.basename(sourcePath),
  sourceHash,
  shuffleQuestions: false,
  shuffleOptions: false,
  mcqs: questions
}

const generatedSource = `// Generated by scripts/build-o6u-physical-therapy-mcqs.mjs.
// ${path.basename(sourcePath)} SHA-256: ${sourceHash}
// Included: ${questions.length} answer-keyed O6U PT-PHYS questions.
(() => {
  const quizzes = window.mcqQuizzesO6u || (window.mcqQuizzesO6u = {})
  quizzes[${JSON.stringify(quizTopicKey)}] = {
    alwaysShowSourcePicker: true,
    sources: [${JSON.stringify(source, null, 2)}]
  }
})()
`

await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))
console.log(JSON.stringify({
  sourcePath,
  sourceHash,
  included: questions.length,
  outputs: targetPaths
}, null, 2))
