import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultSource = 'G:\\school\\study mode\\subjects\\402\\h\\neuro_extra_questions.json'
const sourcePath = path.resolve(process.argv[2] || defaultSource)
const targetPaths = [
  path.join(repoRoot, 'src', 'med402-neuro-extra-mcqs.js'),
  path.join(repoRoot, 'public', 'src', 'med402-neuro-extra-mcqs.js')
]

const sectionDefinitions = [
  { name: 'Introduction', id: 'introduction', label: 'Introduction' },
  { name: 'Hemiplegia', id: 'hemiplegia', label: 'Hemiplegia' },
  { name: 'Hemiplegia (Cranial nerve / brainstem)', id: 'cranial-nerve-brainstem', label: 'Cranial nerve / brainstem' },
  { name: 'Speech and Cranial Nerve', id: 'speech-and-cranial-nerve', label: 'Speech and Cranial Nerve' },
  { name: 'Multiple Sclerosis', id: 'multiple-sclerosis', label: 'Multiple Sclerosis' }
]

function cleanText(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:?!])/g, '$1')
    .trim()
}

function normalizeAnswer(answer) {
  return cleanText(answer).toLowerCase()
}

function parseQuestion(question) {
  const section = sectionDefinitions.find((item) => item.name === question.section)
  const choices = Array.isArray(question.options)
    ? question.options.map((option) => ({
      label: cleanText(option.label).toLowerCase(),
      text: cleanText(option.text)
    }))
    : []
  const answer = normalizeAnswer(question.answer)
  const answerIndex = choices.findIndex((choice) => choice.label === answer)
  const questionText = cleanText(question.question)
  const source = cleanText(`Neurology extra question set - Q${question.id}`)

  if (!section || !questionText || choices.length < 2 || answerIndex < 0) {
    return {
      held: {
        section: question.section || '',
        originalNumber: String(question.id),
        question: questionText,
        choices: choices.map((choice) => choice.text),
        answer: cleanText(question.answer),
        source,
        reason: choices.length < 2
          ? `Incomplete source record: ${choices.length} choices`
          : `Unresolved answer "${cleanText(question.answer)}"`
      }
    }
  }

  return {
    parsed: {
      id: `med402-neuro-extra-q${String(question.id).padStart(3, '0')}`,
      originalNumber: String(question.id),
      category: section.label,
      organ: section.label,
      question: questionText,
      choices: choices.map((choice) => choice.text),
      answerIndex,
      explanation: `Answer: ${choices[answerIndex].text}.`,
      source,
      section: `${section.label} - ${source}`,
      answerHighlightedInSource: Boolean(question.answer_highlighted_in_source),
      sourceNote: cleanText(question.note || ''),
      topicTags: ['MED402-2', 'Neurology', section.label]
    }
  }
}

function createParts(section, sourceId) {
  const partSize = 30
  const parts = []

  for (let offset = 0; offset < section.questions.length; offset += partSize) {
    const questions = section.questions.slice(offset, offset + partSize)
    const index = parts.length
    parts.push({
      id: `med402-neuro-extra-${section.id}-p${String(index + 1).padStart(2, '0')}`,
      label: `Part ${index + 1} - Q${questions[0].originalNumber}-${questions.at(-1).originalNumber}`,
      description: `${section.label} questions`,
      range: `Q${questions[0].originalNumber}-${questions.at(-1).originalNumber}`,
      questionStart: Number(questions[0].originalNumber),
      questionEnd: Number(questions.at(-1).originalNumber),
      parentSourceId: sourceId,
      groupId: section.id,
      groupLabel: section.label,
      partIndex: index,
      partCount: Math.ceil(section.questions.length / partSize),
      shuffleQuestions: false,
      shuffleOptions: false,
      mcqs: questions
    })
  }

  return parts
}

function buildGeneratedSource(sections, heldForReview, bank, sourceHash) {
  const sourceId = 'med402-neuro-extra-question-set'
  const questions = sections.flatMap((section) => section.questions)
  const groups = sections.map((section) => ({
    id: section.id,
    label: section.label,
    questionCount: section.questions.length,
    parts: createParts(section, sourceId)
  }))
  const partCount = groups.reduce((total, group) => total + group.parts.length, 0)

  return `// Generated by scripts/build-med402-neuro-extra-mcqs.mjs.
// Source SHA-256: ${sourceHash}
// Included: ${questions.length} answer-keyed neurology extra questions across ${sections.length} sections.
(() => {
  const quizzes = window.mcqQuizzes402 || (window.mcqQuizzes402 = {})
  const quiz = quizzes["MED 402-2 MCQs"] || (quizzes["MED 402-2 MCQs"] = { alwaysShowSourcePicker: true, sources: [] })
  quiz.alwaysShowSourcePicker = true

  const source = ${JSON.stringify({
    id: sourceId,
    label: 'Old Midterm Neuro MCQs',
    description: `${questions.length} questions - ${sections.length} sections - ${partCount} short parts`,
    sourceTitle: cleanText(bank.title),
    sourceFile: cleanText(bank.source_file),
    note: cleanText(bank.note),
    shuffleQuestions: false,
    shuffleOptions: false,
    mcqs: questions,
    heldForReview,
    collection: {
      prompt: 'Choose an extra neurology section or a revision mode.',
      groupNoun: 'section',
      groupEyebrow: 'MED402-2 neurology extra',
      mixedMeta: 'Random questions from the extra MED402-2 neurology set.',
      mixedSizes: [
        { id: 'quick-20', label: 'Quick 20', size: 20, description: 'A short mixed extra-neurology session.' },
        { id: 'standard-30', label: 'Standard 30', size: 30, description: 'Balanced extra-neurology practice.' },
        { id: 'full-56', label: 'Full 56', size: 56, description: 'Solve the full extra set.' }
      ],
      wrongReviewId: 'med402-neuro-extra-wrong-review',
      groups
    }
  }, null, 2)}

  quiz.sources = (quiz.sources || []).filter((item) => item.id !== source.id)
  quiz.sources.push(source)
})()
`
}

const json = await readFile(sourcePath, 'utf8')
const bank = JSON.parse(json)
const bySection = Object.fromEntries(sectionDefinitions.map((section) => [section.name, { ...section, questions: [] }]))
const heldForReview = []

for (const rawQuestion of bank.questions || []) {
  const result = parseQuestion(rawQuestion)
  if (result.parsed) {
    bySection[rawQuestion.section].questions.push(result.parsed)
  } else {
    heldForReview.push(result.held)
  }
}

const sections = sectionDefinitions.map((section) => bySection[section.name])
const questions = sections.flatMap((section) => section.questions)

if (bank.total_questions !== 56 || (bank.questions || []).length !== 56) {
  throw new Error(`Expected 56 source records, got ${bank.questions?.length || 0}`)
}
if (questions.length + heldForReview.length !== 56) {
  throw new Error(`Expected 56 accounted records, got ${questions.length} included and ${heldForReview.length} held`)
}
if (questions.length !== 56 || heldForReview.length !== 0) {
  throw new Error(`Expected 56 included and 0 held, got ${questions.length} included and ${heldForReview.length} held`)
}
if (new Set(questions.map((question) => question.id)).size !== questions.length) {
  throw new Error('Generated MED402 neuro extra question IDs are not unique')
}
if (questions.some((question) => question.choices.length < 2 || !question.choices[question.answerIndex])) {
  throw new Error('Generated MED402 neuro extra questions contain an invalid answer')
}

const sourceHash = createHash('sha256').update(json).digest('hex')
const generatedSource = buildGeneratedSource(sections, heldForReview, bank, sourceHash)
await Promise.all(targetPaths.map((targetPath) => writeFile(targetPath, generatedSource, 'utf8')))

