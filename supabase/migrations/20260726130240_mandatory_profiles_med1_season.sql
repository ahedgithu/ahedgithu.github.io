-- Require a public student profile and introduce a fresh MED-1 leaderboard season.
-- Existing quiz progress remains untouched. Lifetime best scores are snapshotted
-- before the new season starts, and the season begins at migration time.

ALTER TABLE public.user_preferences
  ADD COLUMN IF NOT EXISTS profile_setup_version INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.user_preferences
  ALTER COLUMN anonymous SET DEFAULT false;

UPDATE public.user_preferences
SET anonymous = false
WHERE anonymous = true;

ALTER TABLE public.user_preferences
  DROP CONSTRAINT IF EXISTS user_preferences_public_identity_required;

ALTER TABLE public.user_preferences
  ADD CONSTRAINT user_preferences_public_identity_required
  CHECK (
    anonymous = false
    AND (
      profile_setup_version = 0
      OR (
        profile_setup_version >= 1
        AND NULLIF(btrim(nickname), '') IS NOT NULL
        AND NULLIF(avatar_id, '') IS NOT NULL
      )
    )
  );

CREATE UNIQUE INDEX IF NOT EXISTS user_preferences_nickname_unique
  ON public.user_preferences (lower(btrim(nickname)))
  WHERE NULLIF(btrim(nickname), '') IS NOT NULL;

ALTER TABLE public.user_mcq_progress
  ADD COLUMN IF NOT EXISTS attempt_id UUID,
  ADD COLUMN IF NOT EXISTS attempt_started_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.leaderboard_seasons (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section           TEXT NOT NULL CHECK (section IN ('401', '402')),
  name              TEXT NOT NULL,
  scope_topic_label TEXT,
  starts_at         TIMESTAMPTZ NOT NULL,
  ends_at           TIMESTAMPTZ,
  active            BOOLEAN NOT NULL DEFAULT true,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS leaderboard_seasons_one_active_per_section
  ON public.leaderboard_seasons (section)
  WHERE active;

CREATE TABLE IF NOT EXISTS public.user_lifetime_scores (
  user_id         UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  section         TEXT NOT NULL,
  topic_label     TEXT NOT NULL,
  source_id       TEXT NOT NULL,
  best_score      INTEGER NOT NULL CHECK (best_score >= 0),
  total_questions INTEGER,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, section, topic_label, source_id)
);

CREATE TABLE IF NOT EXISTS public.user_season_scores (
  season_id       BIGINT NOT NULL REFERENCES public.leaderboard_seasons(id) ON DELETE CASCADE,
  user_id         UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  topic_label     TEXT NOT NULL,
  source_id       TEXT NOT NULL,
  best_score      INTEGER NOT NULL CHECK (best_score >= 0),
  total_questions INTEGER,
  attempt_id      UUID,
  earned_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (season_id, user_id, topic_label, source_id)
);

ALTER TABLE public.leaderboard_seasons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_lifetime_scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_season_scores ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.leaderboard_seasons FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.user_lifetime_scores FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.user_season_scores FROM PUBLIC, anon, authenticated;

INSERT INTO public.user_lifetime_scores (
  user_id,
  section,
  topic_label,
  source_id,
  best_score,
  total_questions,
  updated_at
)
SELECT
  progress.user_id,
  progress.section,
  progress.topic_label,
  progress.source_id,
  GREATEST(COALESCE(progress.score, 0), 0),
  progress.total_questions,
  COALESCE(progress.updated_at, now())
FROM public.user_mcq_progress progress
WHERE progress.score IS NOT NULL
ON CONFLICT (user_id, section, topic_label, source_id)
DO UPDATE SET
  best_score = GREATEST(public.user_lifetime_scores.best_score, EXCLUDED.best_score),
  total_questions = COALESCE(EXCLUDED.total_questions, public.user_lifetime_scores.total_questions),
  updated_at = GREATEST(public.user_lifetime_scores.updated_at, EXCLUDED.updated_at);

INSERT INTO public.leaderboard_seasons (
  section,
  name,
  scope_topic_label,
  starts_at,
  active
)
SELECT
  '401',
  'MED-1 Midterm',
  'MED 401-1 MCQs',
  transaction_timestamp(),
  true
WHERE NOT EXISTS (
  SELECT 1
  FROM public.leaderboard_seasons season
  WHERE season.section = '401'
    AND season.active
);

